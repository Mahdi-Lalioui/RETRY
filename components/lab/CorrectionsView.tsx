'use client';
import { useCallback, useEffect, useMemo, useState } from 'react';
import { AnimatePresence, motion } from 'motion/react';
import type { Correction } from '@/lib/db/schema';
import { Diff, RuleChip, SourceBadge, Stat, Tabs, actionText, labelFor, snapshotOf } from './ui';
import { RescueQueue } from './RescueQueue';

type Row = Omit<Correction, 'createdAt'> & { createdAt: string };
type Mode = 'ledger' | 'queue';

const spring = { type: 'spring' as const, stiffness: 260, damping: 26 };
const RULES = ['R1', 'R2', 'R3', 'R4', 'R5', 'R6', 'R7', 'BUG', 'stuck'];
const SOURCES = ['human', 'scripted', 'augmented'];
const STATUSES = ['queued', 'sent', 'trained', 'failed'];

export function CorrectionsView() {
  const [rows, setRows] = useState<Row[] | null>(null);
  const [mode, setMode] = useState<Mode>('ledger');
  const [rule, setRule] = useState<string | null>(null);
  const [source, setSource] = useState<string | null>(null);
  const [status, setStatus] = useState<string | null>(null);
  const [q, setQ] = useState('');
  const [open, setOpen] = useState<Row | null>(null);
  const [limit, setLimit] = useState(150);

  const load = useCallback(async () => {
    await fetch('/api/demo/bootstrap', { method: 'POST' }).catch(() => null);
    const j = await (await fetch('/api/corrections?limit=1000', { cache: 'no-store' })).json();
    if (j.ok) setRows(groupByParent(j.data as Row[]));
  }, []);
  useEffect(() => { void load(); }, [load]);
  useEffect(() => { if (new URLSearchParams(window.location.search).get('mode') === 'queue') setMode('queue'); }, []);

  const byId = useMemo(() => new Map((rows ?? []).map((r) => [r.id, r])), [rows]);
  const children = useMemo(() => {
    const m = new Map<string, number>();
    for (const r of rows ?? []) if (r.parentId) m.set(r.parentId, (m.get(r.parentId) ?? 0) + 1);
    return m;
  }, [rows]);
  const filtered = useMemo(() => (rows ?? []).filter((r) =>
    (!rule || (rule === 'stuck' ? !r.rule : r.rule === rule)) && (!source || r.source === source) && (!status || r.status === status)
    && (!q || `${r.goal} ${r.id} ${r.semKey ?? ''} ${r.mubitFeedbackId ?? ''}`.toLowerCase().includes(q.toLowerCase()))), [rows, rule, source, status, q]);

  const counts = (rows ?? []).reduce((a, r) => { a[r.source] = (a[r.source] ?? 0) + 1; return a; }, {} as Record<string, number>);
  const rescues = (counts.human ?? 0) + (counts.scripted ?? 0);
  const bugPct = rows?.length ? Math.round((rows.filter((r) => r.goodAction?.type === 'report_bug').length / rows.length) * 100) : 0;

  return (
    <main className="mx-auto max-w-[1680px] px-6 pb-16 pt-8">
      <div className="flex flex-wrap items-end justify-between gap-6">
        <div>
          <div className="text-[11px] font-semibold uppercase tracking-[0.2em] text-[var(--rx-rescue)]">Corrections ledger</div>
          <h1 className="mt-1 text-[34px] font-semibold tracking-[-0.03em]">Every rescue, exactly as Mubit received it.</h1>
          <p className="mt-2 max-w-[900px] text-[15px] muted">
            Click a row to see the training pair: the exact input messages of the call that went wrong and the preferred output.
            <span className="ml-1">Sources are labelled: <SourceBadge source="human" /> a person clicked, <SourceBadge source="scripted" /> overnight backlog generated by the solver, <SourceBadge source="augmented" /> the same decision re-rendered on another training layout.</span>
          </p>
        </div>
        <Tabs<Mode> value={mode} onChange={setMode} tabs={[{ id: 'ledger', label: 'Ledger', hint: String(rows?.length ?? '') }, { id: 'queue', label: 'Rescue queue' }]} />
      </div>

      <div className="mt-6 grid grid-cols-2 gap-3 lg:grid-cols-5">
        <Stat label="Rescues" value={rescues} sub={<>{counts.human ?? 0} human · {counts.scripted ?? 0} scripted</>} color="#F59E0B" />
        <Stat label="Training examples" value={rows?.length ?? '—'} sub={<>{counts.augmented ?? 0} augmented (×8 per rescue)</>} />
        <Stat label="Bug-report pairs" value={`${bugPct}%`} sub={<>target ≥25% so it never learns “always done”</>} />
        <Stat label="Sent to Mubit" value={(rows ?? []).filter((r) => r.mubitFeedbackId).length} sub={<>feedback ids stored per row</>} />
        <Stat label="In a version" value={(rows ?? []).filter((r) => r.versionId).length} sub={<>{(rows ?? []).filter((r) => !r.versionId).length} queued since last refresh</>} />
      </div>

      {mode === 'queue' ? <div className="mt-6"><RescueQueue onCorrection={() => void load()} /></div> : (
        <div className="panel mt-6 overflow-hidden">
          <div className="flex flex-wrap items-center gap-3 border-b hairline px-4 py-3">
            <Filter label="Rule" values={RULES} value={rule} onChange={setRule} />
            <Filter label="Source" values={SOURCES} value={source} onChange={setSource} />
            <Filter label="Status" values={STATUSES} value={status} onChange={setStatus} />
            <input className="input ml-auto w-[280px]" placeholder="Search goal, id, semKey, feedback id…" value={q} onChange={(e) => setQ(e.target.value)} />
          </div>
          {!rows ? <div className="p-6 muted sweep">Loading ledger…</div> : (
            <div className="scroll-thin overflow-x-auto">
              <table className="w-full text-[13px]">
                <thead className="bg-black/20 text-[11px] uppercase tracking-[0.1em] muted">
                  <tr>
                    {['Time', 'Rule', 'Source', 'Parent', 'Lane · seed', 'Correction', 'Status', 'Mubit feedback id'].map((h) => <th key={h} className="whitespace-nowrap px-4 py-2.5 text-left font-medium">{h}</th>)}
                  </tr>
                </thead>
                <tbody>
                  {filtered.slice(0, limit).map((r) => {
                    const snap = snapshotOf(r.messages);
                    return (
                      <tr key={r.id} onClick={() => setOpen(r)} className={`cursor-pointer border-t hairline transition-colors hover:bg-white/[0.025] ${open?.id === r.id ? 'bg-white/[0.04]' : ''}`}>
                        <td className="num whitespace-nowrap px-4 py-2.5 text-[12px] muted">{new Date(r.createdAt).toLocaleTimeString('en-GB')}</td>
                        <td className="px-4 py-2.5"><RuleChip rule={r.rule} small /></td>
                        <td className="px-4 py-2.5"><SourceBadge source={r.source} count={r.source !== 'augmented' && children.get(r.id) ? undefined : undefined} />{r.source !== 'augmented' && children.get(r.id) ? <span className="ml-1.5 mono text-[10px] text-[#A78BFA]">+{children.get(r.id)}</span> : null}</td>
                        <td className="mono px-4 py-2.5 text-[11px] faint">{r.parentId ? r.parentId.slice(-8) : '—'}</td>
                        <td className="mono whitespace-nowrap px-4 py-2.5 text-[12px] muted">{r.lane ?? '—'} · {r.seed ?? '—'}</td>
                        <td className="px-4 py-2.5"><Diff bad={r.badAction} good={r.goodAction} labelBad={labelFor(snap, r.badAction?.target)} labelGood={labelFor(snap, r.goodAction.target)} /></td>
                        <td className="px-4 py-2.5"><StatusDot s={r.status} /></td>
                        <td className="mono px-4 py-2.5 text-[11px] faint">{r.mubitFeedbackId ?? '—'}</td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
              {filtered.length > limit && <div className="border-t hairline p-3 text-center"><button className="btn" onClick={() => setLimit((l) => l + 300)}>Show more ({filtered.length - limit})</button></div>}
              {!filtered.length && <div className="p-8 text-center muted">No corrections match.</div>}
            </div>
          )}
        </div>
      )}
      <PairDrawer row={open} parent={open?.parentId ? byId.get(open.parentId) ?? null : null} siblings={open ? (rows ?? []).filter((r) => r.parentId === (open.parentId ?? open.id)).length : 0} onClose={() => setOpen(null)} onOpen={setOpen} />
    </main>
  );
}

/** Newest rescue first, each followed by its augmented copies. */
function groupByParent(rows: Row[]): Row[] {
  const kids = new Map<string, Row[]>();
  const roots: Row[] = [];
  for (const r of rows) {
    if (r.parentId && rows.some((x) => x.id === r.parentId)) kids.set(r.parentId, [...(kids.get(r.parentId) ?? []), r]);
    else roots.push(r);
  }
  return roots.flatMap((r) => [r, ...(kids.get(r.id) ?? [])]);
}

function Filter({ label, values, value, onChange }: { label: string; values: string[]; value: string | null; onChange: (v: string | null) => void }) {
  return (
    <div className="flex items-center gap-1">
      <span className="mr-1 text-[11px] uppercase tracking-[0.1em] faint">{label}</span>
      {values.map((v) => (
        <button key={v} onClick={() => onChange(value === v ? null : v)}
          className={`mono rounded-md border px-2 py-0.5 text-[11px] transition-colors ${value === v ? 'border-[#22D3EE88] bg-[#22D3EE14] text-[#A5F3FC]' : 'border-transparent muted hover:text-[var(--rx-text)]'}`}>{v}</button>
      ))}
    </div>
  );
}

function StatusDot({ s }: { s: string }) {
  const c = s === 'trained' ? '#22D3EE' : s === 'sent' ? '#FF4500' : s === 'failed' ? '#F43F5E' : '#F59E0B';
  return (
    <span className="inline-flex items-center gap-1.5 text-[12px]">
      <span className={`h-2 w-2 rounded-full ${s === 'queued' ? 'pulse' : ''}`} style={{ background: c, boxShadow: `0 0 8px ${c}` }} />
      <span style={{ color: c }}>{s === 'trained' ? 'in version' : s}</span>
    </span>
  );
}

function PairDrawer({ row, parent, siblings, onClose, onOpen }: { row: Row | null; parent: Row | null; siblings: number; onClose: () => void; onOpen: (r: Row) => void }) {
  const [showSystem, setShowSystem] = useState(false);
  useEffect(() => {
    const k = (e: KeyboardEvent) => { if (e.key === 'Escape') onClose(); };
    window.addEventListener('keydown', k); return () => window.removeEventListener('keydown', k);
  }, [onClose]);
  const preferred = row ? JSON.stringify(row.goodAction, null, 2) : '';
  return (
    <AnimatePresence>
      {row && (
        <>
          <motion.div className="fixed inset-0 z-40 bg-black/60 backdrop-blur-[2px]" initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }} onClick={onClose} />
          <motion.aside key={row.id} className="fixed bottom-0 right-0 top-0 z-50 flex w-[min(920px,95vw)] flex-col border-l hairline bg-[var(--rx-panel)] shadow-2xl"
            initial={{ x: 40, opacity: 0 }} animate={{ x: 0, opacity: 1 }} exit={{ x: 40, opacity: 0 }} transition={spring}>
            <div className="flex items-start gap-4 border-b hairline px-6 py-4">
              <div className="min-w-0">
                <div className="text-[11px] font-semibold uppercase tracking-[0.16em] muted">Training pair · as sent to Mubit</div>
                <div className="mt-2 flex flex-wrap items-center gap-2">
                  <RuleChip rule={row.rule} /><SourceBadge source={row.source} />
                  <span className="mono text-[11px] faint">{row.id}</span>
                </div>
                <div className="mt-2 truncate text-[14px]">{row.goal}</div>
              </div>
              <button className="btn ml-auto shrink-0" onClick={onClose}>Close <kbd>Esc</kbd></button>
            </div>
            <div className="scroll-thin min-h-0 flex-1 overflow-y-auto p-6">
              {row.source === 'augmented' && (
                <div className="mb-4 rounded-lg border border-[#A78BFA44] bg-[#A78BFA0D] p-3 text-[12px] leading-5 text-[#C4B5FD]">
                  Augmented: the same {parent?.source ?? 'human'} decision re-rendered on training seed <b className="mono">{row.seed}</b> — equivalent state (page, cart, modals, inputs), element found by its stable semantic key <span className="mono">{row.semKey ?? '—'}</span>, ids remapped in the snapshot and history.
                  {parent && <button className="ml-2 underline" onClick={() => onOpen(parent)}>Open parent →</button>}
                </div>
              )}
              {row.source === 'scripted' && (
                <div className="mb-4 rounded-lg border border-[#FACC1544] bg-[#FACC150D] p-3 text-[12px] leading-5 text-[#FDE68A]">
                  Scripted (not a human): from the overnight backlog — base v1 ran on training seed <b className="mono">{row.seed}</b> and, at this stuck point, the correct action came from the shop’s rule-following solver. {siblings} augmented copies.
                </div>
              )}
              <div className="grid grid-cols-1 gap-4 lg:grid-cols-2">
                <div className="panel-2 p-4">
                  <div className="text-[11px] uppercase tracking-[0.12em] text-[#F43F5E]">bad output (what the model did)</div>
                  <pre className="mono mt-2 whitespace-pre-wrap text-[12px] text-[#FDA4AF]">{row.badAction ? JSON.stringify(row.badAction, null, 2) : '— (augmented copy: only the preferred output is sent)'}</pre>
                </div>
                <div className="panel-2 p-4" style={{ borderColor: '#34D39944' }}>
                  <div className="text-[11px] uppercase tracking-[0.12em] text-[#34D399]">preferred_output</div>
                  <pre className="mono mt-2 whitespace-pre-wrap text-[12px] text-[#A7F3D0]">{preferred}</pre>
                </div>
              </div>
              <div className="mt-5 flex items-center justify-between">
                <div className="text-[11px] uppercase tracking-[0.12em] muted">input messages ({row.messages.length})</div>
                <button className="text-[12px] muted underline-offset-2 hover:underline" onClick={() => setShowSystem((x) => !x)}>{showSystem ? 'hide' : 'show'} system prompt</button>
              </div>
              {row.messages.map((m, i) => (m.role === 'system' && !showSystem ? (
                <div key={i} className="mt-2 rounded-lg border hairline px-4 py-2 text-[12px] muted"><span className="mono">system</span> · {m.content.length} chars · “…Follow house test policy.” (rules are never listed)</div>
              ) : (
                <div key={i} className="mt-2 overflow-hidden rounded-lg border hairline">
                  <div className="mono border-b hairline bg-black/20 px-4 py-1.5 text-[11px] muted">{m.role}</div>
                  <pre className="mono whitespace-pre-wrap bg-[#05070A] p-4 text-[12px] leading-[1.7] text-[#C9D1DC]">{highlight(m.content, row.goodAction.target)}</pre>
                </div>
              )))}
              <div className="mt-4 grid grid-cols-2 gap-2 text-[12px] md:grid-cols-4">
                {[['status', row.status], ['mubit feedback id', row.mubitFeedbackId ?? '—'], ['version', row.versionId ?? 'queued'], ['run', row.runId ?? '—']].map(([k, v]) => (
                  <div key={k} className="rounded-lg bg-black/20 px-3 py-2"><div className="text-[10px] uppercase tracking-[0.1em] faint">{k}</div><div className="mono mt-0.5 truncate">{v}</div></div>
                ))}
              </div>
              <div className="mt-3 mono text-[11px] faint">good action: {actionText(row.goodAction)} — {row.goodAction.reason}</div>
            </div>
          </motion.aside>
        </>
      )}
    </AnimatePresence>
  );
}

function highlight(text: string, target?: string) {
  if (!target) return text;
  const re = new RegExp(`(\\b${target} \\w+ "[^"]*")`, 'g');
  return text.split(re).map((p, i) => (i % 2 === 1 ? <mark key={i} className="rounded bg-[#34D39926] px-0.5 text-[#A7F3D0]">{p}</mark> : <span key={i}>{p}</span>));
}
